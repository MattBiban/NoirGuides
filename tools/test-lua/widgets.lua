local function sized(c, parent, w, h)
  local f = c.G.CreateFrame("Frame", nil, parent or c.G.UIParent)
  f:SetSize(w, h)
  return f
end

test("rectOf resolves chains of anchors with scale", function()
  local c = bare()
  local G = c.G
  eq({ c:rectOf(G.UIParent) }, { 0, 0, 1024, 768 })
  local a = sized(c, nil, 200, 100)
  a:SetPoint("TOPLEFT", G.UIParent, "TOPLEFT", 10, -20)
  eq({ c:rectOf(a) }, { 10, 648, 210, 748 })
  -- b hangs below a, at twice the scale: its size and offsets count double in UIParent units.
  local b = sized(c, a, 50, 40)
  b:SetScale(2)
  b:SetPoint("TOP", a, "BOTTOM", 5, -10)
  eq({ c:rectOf(b) }, { 70, 548, 170, 628 })
  -- This one is stretched between two anchors and takes its width from them, not from its own size.
  local stretched = sized(c, a, 1, 30)
  stretched:SetPoint("TOPLEFT", a, "BOTTOMLEFT", 0, 0)
  stretched:SetPoint("TOPRIGHT", a, "BOTTOMRIGHT", -100, 0)
  eq({ c:rectOf(stretched) }, { 10, 618, 110, 648 })
  eq(stretched:GetWidth(), 100, "the width follows the anchors")
  -- SetAllPoints copies the rectangle of another frame.
  local cover = c.G.CreateFrame("Frame", nil, b)
  cover:SetAllPoints(b)
  eq({ c:rectOf(cover) }, { 70, 548, 170, 628 })
  eq(c:rectOf(c.G.CreateFrame("Frame", nil, G.UIParent)), nil, "a frame without an anchor has no rectangle")
end)

test("the UI scale and the resolution set the size of UIParent, as in the game", function()
  local cases = {
    { { w = 1024, h = 768, scale = 1 }, 1024, 768 },
    { { w = 1920, h = 1080, scale = 0.64 }, 768 * 1920 / 1080 / 0.64, 1200 },
    { { w = 3840, h = 1080, scale = 1 }, 768 * 3840 / 1080, 768 },
  }
  for _, case in ipairs(cases) do
    local c = Client.new({ files = {}, screen = case[1] })
    local G = c.G
    near(G.GetScreenWidth(), case[2], 1e-6)
    near(G.GetScreenHeight(), case[3], 1e-6)
    near(G.UIParent:GetWidth(), case[2], 1e-6)
    near(G.UIParent:GetEffectiveScale(), case[1].scale, 1e-9)
    local _, _, right, top = c:rectOf(G.UIParent)
    near(right, case[2], 1e-6)
    near(top, case[3], 1e-6)
    -- A frame's own coordinates times its effective scale over UIParent's are UIParent units.
    local f = c.G.CreateFrame("Frame", nil, G.UIParent)
    f:SetSize(100, 100)
    f:SetScale(1.5)
    f:SetPoint("BOTTOMLEFT", G.UIParent, "BOTTOMLEFT", 20, 30)
    near(f:GetLeft() * f:GetEffectiveScale() / G.UIParent:GetEffectiveScale(), 30, 1e-6)
    near(f:GetTop() * f:GetEffectiveScale() / G.UIParent:GetEffectiveScale(), 45 + 150, 1e-6)
  end
end)

test("offScreen lists a shown frame that leaves the screen and ignores hidden ones", function()
  local c = bare()
  local G = c.G
  local inside = sized(c, nil, 100, 100)
  inside:SetPoint("CENTER")
  eq(c:offScreen(), {})
  local out = c.G.CreateFrame("Frame", "NoirGuidesSampleOut", G.UIParent)
  out:SetSize(100, 100)
  out:SetPoint("TOPLEFT", G.UIParent, "TOPLEFT", -30, 0)
  local below = sized(c, inside, 20, 20)
  below:SetPoint("TOP", G.UIParent, "BOTTOM", 0, 5)
  eq(#c:offScreen(), 2)
  eq(c:offScreen()[1], "NoirGuidesSampleOut", "a named frame is listed by its name")
  ok(c:offScreen()[2]:find("Frame"), "an unnamed one by a label")
  out:Hide()
  inside:Hide()
  eq(c:offScreen(), {}, "hidden frames, and frames inside hidden ones, do not count")
  inside:Show()
  below:ClearAllPoints()
  below:SetPoint("CENTER")
  eq(c:offScreen(), {})
  -- Frames clipped away by a scroll frame are not drawn.
  local scroll = c.G.CreateFrame("ScrollFrame", nil, G.UIParent)
  scroll:SetSize(100, 100)
  scroll:SetPoint("CENTER")
  local child = sized(c, scroll, 100, 2000)
  scroll:SetScrollChild(child)
  eq(c:offScreen(), {}, "a long scroll child is clipped by its scroll frame")
  scroll:SetVerticalScroll(500)
  eq(scroll:GetVerticalScroll(), 500)
  eq(c:offScreen(), {})
end)

test("changing the resolution fires the display events", function()
  local c = bare()
  local G = c.G
  local seen = {}
  local f = G.CreateFrame("Frame")
  f:RegisterEvent("DISPLAY_SIZE_CHANGED")
  f:RegisterEvent("UI_SCALE_CHANGED")
