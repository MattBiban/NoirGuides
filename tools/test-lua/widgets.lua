test("the mouse: cursor, clicks, double clicks, the wheel and the tooltip", function()
  local c = bare()
  local G = c.G
  c:setCursor(100, 200)
  eq({ G.GetCursorPosition() }, { 100, 200 })
  local scaled = Client.new({ files = {}, screen = { w = 1920, h = 1080, scale = 0.64 } })
  scaled:setCursor(100, 200)
  local x, y = scaled.G.GetCursorPosition()
  near(x / scaled.G.UIParent:GetEffectiveScale(), 100, 1e-9, "the cursor divided by UIParent's scale is in UIParent units")
  near(y / scaled.G.UIParent:GetEffectiveScale(), 200, 1e-9)

  local button = G.CreateFrame("Button", nil, G.UIParent)
  button:SetSize(20, 20)
  button:SetPoint("CENTER")
  button:EnableMouse(true)
  local log = {}
  button:SetScript("OnClick", function(_, which) log[#log + 1] = "click " .. which end)
  button:SetScript("OnDoubleClick", function() log[#log + 1] = "double" end)
  button:SetScript("PreClick", function() log[#log + 1] = "pre" end)
  button:SetScript("PostClick", function() log[#log + 1] = "post" end)
  c:click(button, "RightButton")
  eq(log, { "pre", "click RightButton", "post" })
  log = {}
  c:doubleClick(button, 0.2)
  eq(log, { "pre", "click LeftButton", "post", "double" })
  log = {}
  c:doubleClick(button, 0.6)
  eq(log, { "pre", "click LeftButton", "post", "pre", "click LeftButton", "post" }, "too slow for a double click")

  local wheeled = 0
  button:SetScript("OnMouseWheel", function(_, delta) wheeled = wheeled + delta end)
  eq(c:wheel(button, -1), false, "no wheel until EnableMouseWheel")
  button:EnableMouseWheel(true)
  eq(c:wheel(button, -1), true)
  eq(c:wheel(button, 3), true)
  eq(wheeled, 2)

  button:SetScript("OnEnter", function(self)
    G.GameTooltip:SetOwner(self, "ANCHOR_RIGHT")
    G.GameTooltip:AddLine("Mindless Zombie")
    G.GameTooltip:AddDoubleLine("Level", "2")
    G.GameTooltip:Show()
  end)
  button:SetScript("OnLeave", function() G.GameTooltip:Hide() end)
  eq(c:tooltip(), {})
  c:hover(button)
  eq(c:tooltip(), { "Mindless Zombie", "Level 2" })
  eq(G.GameTooltip:GetOwner(), button)
  c:hover(button, true)
  eq(c:tooltip(), {})
  G.GameTooltip:SetOwner(button, "ANCHOR_NONE")
  G.GameTooltip:SetHyperlink("quest:364")
  G.GameTooltip:Show()
  eq(c:tooltip()[1], "The Mindless Ones", "a quest link shows the quest's title")
  eq(c:offScreen(), {})
end)

test("modifier keys and key presses", function()
  local c = bare()
  local G = c.G
  eq({ G.IsControlKeyDown(), G.IsShiftKeyDown(), G.IsAltKeyDown(), G.IsModifierKeyDown() }, { false, false, false, false })
  c:hold("ALT", true)
  eq({ G.IsAltKeyDown(), G.IsModifierKeyDown() }, { true, true })
  c:hold("CTRL", true)
  c:hold("ALT", false)
  eq({ G.IsControlKeyDown(), G.IsAltKeyDown() }, { true, false })
  c:hold("SHIFT", true)
  eq(G.IsShiftKeyDown(), true)
  local keys = {}
  local under = sized(c, nil, 10, 10)
  local top = sized(c, nil, 10, 10)
  under:SetScript("OnKeyDown", function(_, key) keys[#keys + 1] = "under " .. key end)
  top:SetScript("OnKeyDown", function(_, key) keys[#keys + 1] = "top " .. key end)
  eq(c:pressKey("ESCAPE"), false, "no frame takes the keyboard")
  under:EnableKeyboard(true)
  top:EnableKeyboard(true)
  eq(c:pressKey("ESCAPE"), true)
  eq(keys, { "top ESCAPE" }, "the newest frame takes the key and keeps it")
  top:SetPropagateKeyboardInput(true)
  c:pressKey("A")
  eq(keys, { "top ESCAPE", "top A", "under A" }, "a frame that propagates passes the key on")
  c:enterCombat()
  top:SetPropagateKeyboardInput(false)
  has(c:takeViolations()[1], "SetPropagateKeyboardInput")
  c:leaveCombat()
end)

