  eq(text:SetFont("Interface\\AddOns\\NoirGuides\\Fonts\\Missing.ttf", 12, ""), false, "a font file the addon does not ship")
  raises(function() text:SetText("hello") end, "Font not set")
  eq(text:SetFont("Fonts\\FRIZQT__.TTF", 12, ""), true)
  text:SetText("hello")
  eq(text:GetText(), "hello")
  eq(text:GetStringHeight(), 12)
  text:SetText("one\ntwo")
  eq(text:GetNumLines(), 2)
end)

