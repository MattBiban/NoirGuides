test("a frame is visible only while every frame around it is shown, and its scripts follow", function()
  local c = bare()
  local outer = c.G.CreateFrame("Frame", nil, c.G.UIParent)
  local inner = c.G.CreateFrame("Frame", nil, outer)
  local seen, ticks = {}, 0
  inner:SetScript("OnShow", function() seen[#seen + 1] = "show" end)
  inner:SetScript("OnHide", function() seen[#seen + 1] = "hide" end)
  inner:SetScript("OnUpdate", function() ticks = ticks + 1 end)
  eq(inner:IsVisible(), true)
  outer:Hide()
  eq(inner:IsShown(), true)
  eq(inner:IsVisible(), false)
  c:advance(1)
  eq(ticks, 0, "no OnUpdate inside a hidden frame")
  outer:Show()
  c:advance(0.3)
  eq(ticks, 3)
  inner:Hide()
  inner:Hide()
  eq(seen, { "hide", "show", "hide" })
end)

