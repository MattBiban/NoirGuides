end)

test("sizes that change run OnSizeChanged; clamped, click and motion switches are kept", function()
  local c = bare()
  local f = sized(c, nil, 10, 10)
  f:SetPoint("CENTER")
  local sizes = {}
  f:SetScript("OnSizeChanged", function(_, w, h) sizes[#sizes + 1] = w .. "x" .. h end)
  f:SetSize(20, 10)
  f:SetHeight(30)
  f:SetHeight(30)
  eq(sizes, { "20x10", "20x30" })
  f:SetClampedToScreen(true)
  ok(f:IsClampedToScreen())
  f:EnableMouse(true)
  f:SetMouseClickEnabled(false)
  local clicks, entered = 0, 0
  f:SetScript("OnMouseUp", function() clicks = clicks + 1 end)
  f:SetScript("OnEnter", function() entered = entered + 1 end)
  eq(c:click(f), false, "clicks pass through a frame that takes motion only")
  eq(c:hover(f), true)
  f:SetMouseClickEnabled(true)
  f:SetMouseMotionEnabled(false)
  eq(c:click(f), true)
  eq(c:hover(f), false, "no OnEnter without mouse motion")
  eq({ clicks, entered }, { 1, 1 })
  local cooldown = c.G.CreateFrame("Cooldown", nil, f)
  cooldown:SetCooldown(c.now, 10)
  eq({ cooldown:GetCooldownTimes() }, { c.now * 1000, 10000 })
