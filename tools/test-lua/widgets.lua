test("dragging moves a movable frame that takes the mouse, inside the screen when it is clamped", function()
  local c = bare()
  local frame = c.G.CreateFrame("Frame", nil, c.G.UIParent)
  frame:SetSize(100, 50)
  frame:SetPoint("CENTER", c.G.UIParent, "CENTER", 0, 0)
  eq({ frame:GetLeft(), frame:GetTop() }, { 462, 409 })
  eq(c:drag(frame, 10, 10), false, "the mouse passes through")
  frame:EnableMouse(true)
  frame:SetMovable(true)
  frame:RegisterForDrag("LeftButton")
  frame:SetScript("OnDragStart", function(self) self:StartMoving() end)
  frame:SetScript("OnDragStop", function(self) self:StopMovingOrSizing() end)
  eq(c:drag(frame, 10, -20), true)
  eq({ frame:GetLeft(), frame:GetTop() }, { 472, 389 })
  frame:SetClampedToScreen(true)
  c:drag(frame, 5000, 5000)
  eq({ frame:GetRight(), frame:GetTop() }, { 1024, 768 })
  frame:SetScale(2)
  frame:ClearAllPoints()
  frame:SetPoint("TOPLEFT", c.G.UIParent, "BOTTOMLEFT", 100, 200)
  eq({ frame:GetLeft(), frame:GetTop(), frame:GetRight() }, { 100, 200, 200 }, "a frame's own coordinates are in its own scale")
  frame:SetScript("OnDragStop", nil)
  c:drag(frame, 1, 1)
  eq(#c:takeErrors(), 1, "a drag that never stops moving the frame is a mistake in the addon")
end)

