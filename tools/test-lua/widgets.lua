test("text on a font string without a font is an error, as in the game", function()
  local c = bare()
  local text = c.G.CreateFrame("Frame", nil, c.G.UIParent):CreateFontString(nil, "OVERLAY")
  raises(function() text:SetText("hello") end, "Font not set")
