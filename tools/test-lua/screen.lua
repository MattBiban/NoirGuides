-- Screen keeping (plan task E1, spec 4.1): every window opens at its default place or its saved one, is kept fully
-- inside the screen when it opens, grows, is dragged or the resolution changes, and takes part in hide, preview and
-- hide-in-raid. Each test runs at three screens: 1024x768 at scale 1, 1920x1080 at 0.64 and 3840x1080 at 1.
use("tools/test-lua/sample/helper.lua")

local SCREENS = {
  { w = 1024, h = 768, scale = 1 },
  { w = 1920, h = 1080, scale = 0.64 },
  { w = 3840, h = 1080, scale = 1 },
}

local function each(fn)
  for _, screen in ipairs(SCREENS) do
    local c = sample({ screen = screen }):login()
    local W, H = c.G.GetScreenWidth(), c.G.GetScreenHeight()
    fn(c, c.G.Noir.Screen, W, H, screen)
    eq(c:offScreen(), {}, screen.w .. "x" .. screen.h .. " at " .. screen.scale)
  end
end

local function frame(c, w, h)
  local f = c.G.CreateFrame("Frame", nil, c.G.UIParent)
  f:SetSize(w, h)
  return f
end

local function rect(c, f)
  return { c:rectOf(f) }
end

test("each window key has a default place on the screen", function()
  each(function(c, Screen, W, H)
    local keys = {}
    for key in pairs(Screen.DEFAULTS) do keys[#keys + 1] = key end
    table.sort(keys)
    eq(keys, { "arrow", "arrowReset", "dialog", "items", "targets", "window", "wizard" })
    eq(Screen.DEFAULTS.window, { "LEFT", "LEFT", 20, 80 })
    for _, key in ipairs(keys) do
      local f = frame(c, 300, 200)
      Screen.Place(f, key)
      ok(f:IsClampedToScreen(), key .. " is clamped")
      local left, bottom, right, top = c:rectOf(f)
      ok(left >= 0 and bottom >= 0 and right <= W + 1e-6 and top <= H + 1e-6, key .. " is on the screen")
      f:Hide()
    end
    -- The guide window: at the left edge, a little above the vertical middle.
    local window = frame(c, 300, 200)
    Screen.Place(window, "window")
    local left, bottom, _, top = c:rectOf(window)
    near(left, 20, 1e-6)
    near((bottom + top) / 2, H / 2 + 80, 1e-6)
    -- The arrow: top middle.
    local arrow = frame(c, 100, 60)
    Screen.Place(arrow, "arrow")
    local aLeft, _, aRight, aTop = c:rectOf(arrow)
    near((aLeft + aRight) / 2, W / 2, 1e-6)
    near(aTop, H - 100, 1e-6)
  end)
end)

test("a scaled window keeps its default place in screen units", function()
  each(function(c, Screen, _, H)
    local f = frame(c, 300, 200)
    f:SetScale(1.5)
    Screen.Place(f, "window")
    local left, bottom, _, top = c:rectOf(f)
    near(left, 20, 1e-6)
    near((bottom + top) / 2, H / 2 + 80, 1e-6)
  end)
end)

test("a saved place outside the screen is pulled back at login", function()
  for _, screen in ipairs(SCREENS) do
    local c = sample({ screen = { w = 3840, h = 1080, scale = 1 } }):login()
    local Options = c.G.Noir.Options
    Options.SavePosition("window", { "TOPLEFT", "BOTTOMLEFT", 2600, 1000 })
    Options.SavePosition("items", { "TOPLEFT", "BOTTOMLEFT", -400, -50 })
    local again = c:relog({ screen = screen })
    local Screen = again.G.Noir.Screen
    local W, H = again.G.GetScreenWidth(), again.G.GetScreenHeight()
    local window, items = frame(again, 300, 200), frame(again, 200, 40)
    Screen.Place(window, "window")
    Screen.Place(items, "items")
    eq(again:offScreen(), {})
    local left, _, right, top = again:rectOf(window)
    ok(right <= W + 1e-6 and top <= H + 1e-6, "pulled back inside")
    if 2600 + 300 <= W then near(left, 2600, 1e-6, "kept where it was when it fits") end
    local iLeft, iBottom = again:rectOf(items)
    near(iLeft, 0, 1e-6)
    near(iBottom, 0, 1e-6)
  end
end)

test("a frame that grows past the bottom is moved up", function()
  each(function(c, Screen, _, H)
    local f = frame(c, 300, 100)
    Screen.Place(f, "window")
    f:SetHeight(H - 40)
    local _, bottom, _, top = c:rectOf(f)
    ok(bottom >= -1e-6, "the bottom is on the screen")
    ok(top <= H + 1e-6, "and so is the top")
    -- A frame shown again after it grew while hidden is checked when it shows.
    f:Hide()
    f:SetHeight(100)
    f:ClearAllPoints()
    f:SetPoint("TOPLEFT", c.G.UIParent, "BOTTOMLEFT", 10, 50)
    f:Show()
    local _, b2 = c:rectOf(f)
    near(b2, 0, 1e-6)
  end)
end)

test("after a resolution or UI scale change every kept frame is on screen again", function()
  for _, start in ipairs(SCREENS) do
    local c = sample({ screen = start }):login()
    local Screen = c.G.Noir.Screen
    local W, H = c.G.GetScreenWidth(), c.G.GetScreenHeight()
    local right, top = frame(c, 300, 200), frame(c, 300, 200)
    right:SetPoint("TOPLEFT", c.G.UIParent, "BOTTOMLEFT", W - 310, H / 2)
    top:SetPoint("TOPLEFT", c.G.UIParent, "BOTTOMLEFT", 10, H - 5)
    Screen.Keep(right)
    Screen.Keep(top)
    for _, next in ipairs({ { 800, 600, 1 }, { 800, 600, 1.2 }, { 1024, 768, 0.64 }, { 640, 480, 1 } }) do
      c:setScreen(next[1], next[2], next[3])
      eq(c:offScreen(), {}, "after " .. next[1] .. "x" .. next[2] .. " at " .. next[3])
    end
  end
end)

test("Fit caps a tall frame to 90% of the screen", function()
  each(function(c, Screen, _, H)
    eq(Screen.MAX_SHARE, 0.9)
    local f = frame(c, 200, 100)
    Screen.Place(f, "dialog")
    near(Screen.Fit(f, 5000), 0.9 * H, 1e-6)
    near(f:GetHeight(), 0.9 * H, 1e-6)
    eq(Screen.Fit(f, 120), 120)
    f:SetScale(2)
    near(Screen.Fit(f, 5000), 0.45 * H, 1e-6, "in the frame's own units")
  end)
end)

test("AtCursor opens to the right and flips left at the right edge", function()
  each(function(c, Screen, W, H)
    local f = frame(c, 200, 100)
    c:setCursor(100, H - 100)
    eq(Screen.AtCursor(f, "right"), "right")
    local left, _, _, top = c:rectOf(f)
    near(left, 100, 1e-6)
    near(top, H - 100, 1e-6)
    c:setCursor(W - 50, H - 100)
    eq(Screen.AtCursor(f, "right"), "left")
    local _, _, right = c:rectOf(f)
    near(right, W - 50, 1e-6)
    c:setCursor(50, 300)
    eq(Screen.AtCursor(f, "left"), "right", "no room on the left")
    near((c:rectOf(f)), 50, 1e-6)
    c:setCursor(500, 20)
    Screen.AtCursor(f, "right")
    local _, bottom = c:rectOf(f)
    near(bottom, 0, 1e-6, "kept above the bottom edge")
  end)
end)

test("locked frames do not move; Alt-drag moves a frame that allows it", function()
  each(function(c, Screen, W, H)
    local Options = c.G.Noir.Options
    local window = frame(c, 300, 200)
    Screen.Place(window, "window")
    Screen.Movable(window, "window")
    local before = rect(c, window)
    eq(c:drag(window, 30, -20), true)
    local after = rect(c, window)
    near(after[1], before[1] + 30, 1e-6)
    near(after[4], before[4] - 20, 1e-6)
    local saved = Options.Position("window")
    eq({ saved[1], saved[2] }, { "TOPLEFT", "BOTTOMLEFT" })
    near(saved[3], after[1], 1e-6)
    near(saved[4], after[4], 1e-6)
    Options.Set("locked", true)
    c:drag(window, 50, 50)
    eq(rect(c, window), after, "locked: the drag does nothing")
    c:hold("ALT", true)
    c:drag(window, 50, 50)
    eq(rect(c, window), after, "Alt does not unlock the guide window")
    c:hold("ALT", false)

    local items = frame(c, 160, 40)
    Screen.Place(items, "items")
    Screen.Movable(items, "items", { altWhenLocked = true })
    local start = rect(c, items)
    c:drag(items, 40, 0)
    eq(rect(c, items), start, "locked, without Alt")
    c:hold("ALT", true)
    c:drag(items, 40, 0)
    near(rect(c, items)[1], start[1] + 40, 1e-6)
    c:hold("ALT", false)

    -- Resizing by the corner grip or by Alt-drag, saved with the place.
    Options.Set("locked", false)
    local sized = frame(c, 300, 200)
    Screen.Place(sized, "wizard")
    local grip = Screen.Movable(sized, "wizard", { resizable = true })
    ok(grip, "a resizable frame gets a corner grip")
    local corner = rect(c, sized)
    c:drag(grip, 40, -30)
    eq({ sized:GetWidth(), sized:GetHeight() }, { 340, 230 })
    local now = rect(c, sized)
    near(now[1], corner[1], 1e-6, "the top left corner stays")
    near(now[4], corner[4], 1e-6)
    eq({ Options.Position("wizard")[5], Options.Position("wizard")[6] }, { 340, 230 })
    c:hold("ALT", true)
    c:drag(sized, -40, 30)
    c:hold("ALT", false)
    eq({ sized:GetWidth(), sized:GetHeight() }, { 300, 200 })
    Options.Set("locked", true)
    c:drag(grip, 40, -30)
    eq(sized:GetWidth(), 300, "locked: no resizing")
    -- A drag towards an edge stops at it.
    Options.Set("locked", false)
    c:drag(window, -5000, 5000)
    local l, _, _, t = c:rectOf(window)
    near(l, 0, 1e-6)
    near(t, H, 1e-6)
    ok(W > 0)
  end)
end)

test("a saved size comes back with the place", function()
  local c = sample():login()
  c.G.Noir.Options.SavePosition("wizard", { "TOPLEFT", "BOTTOMLEFT", 100, 600, 340, 230 })
  local f = frame(c, 300, 200)
  c.G.Noir.Screen.Place(f, "wizard")
  eq({ f:GetWidth(), f:GetHeight() }, { 340, 230 })
  eq({ c:rectOf(f) }, { 100, 370, 440, 600 })
  c.G.Noir.Screen.Reset("wizard")
  eq(c.G.Noir.Options.Position("wizard"), nil)
  eq(c:offScreen(), {})
end)

test("SetShown hides every registered window and shows them again", function()
  each(function(c, Screen)
    local Options = c.G.Noir.Options
    local window, arrow, wizard = frame(c, 300, 200), frame(c, 80, 60), frame(c, 300, 300)
    Screen.Place(window, "window")
    Screen.Place(arrow, "arrow")
    Screen.Place(wizard, "wizard")
    wizard:Hide()
    Screen.Register("window", window)
    Screen.Register("arrow", arrow)
    Screen.Register("wizard", wizard)
    Screen.SetShown(false)
    eq({ window:IsShown(), arrow:IsShown(), wizard:IsShown(), Options.Get("shown") }, { false, false, false, false })
    wizard:Show() -- a module asks to show its window while everything is hidden
    eq(wizard:IsShown(), false, "it stays hidden")
    Screen.SetShown(true)
    eq({ window:IsShown(), arrow:IsShown(), wizard:IsShown(), Options.Get("shown") }, { true, true, true, true })
    wizard:Hide()
    Screen.SetShown(false)
    Screen.SetShown(true)
    eq(wizard:IsShown(), false, "a window hidden before stays hidden")
  end)
end)

test("the shown setting holds over a relog for windows registered at login", function()
  local c = sample():login()
  c.G.Noir.Screen.SetShown(false)
  local again = c:relog()
  local f = frame(again, 100, 100)
  again.G.Noir.Screen.Place(f, "dialog")
  again.G.Noir.Screen.Register("dialog", f)
  eq(f:IsShown(), false)
  again.G.Noir.Screen.SetShown(true)
  eq(f:IsShown(), true)
  eq(again:offScreen(), {})
end)

test("Preview calls every window's preview and turns it off again", function()
  each(function(c, Screen)
    local calls = {}
    local a, b = frame(c, 100, 100), frame(c, 100, 100)
    Screen.Place(a, "items")
    Screen.Place(b, "targets")
    Screen.Register("items", a, function(on) calls[#calls + 1] = "items " .. tostring(on) end)
    Screen.Register("targets", b, function(on) calls[#calls + 1] = "targets " .. tostring(on) end)
    Screen.Register("dialog", frame(c, 10, 10))
    eq(Screen.IsPreview(), false)
    Screen.Preview(true)
    eq(Screen.IsPreview(), true)
    table.sort(calls)
    eq(calls, { "items true", "targets true" })
    calls = {}
    Screen.Preview(false)
    table.sort(calls)
    eq(calls, { "items false", "targets false" })
    eq(Screen.IsPreview(), false)
  end)
end)

test("hide in raid hides everything in a raid and shows it after", function()
  each(function(c, Screen)
    local Options = c.G.Noir.Options
    local f = frame(c, 100, 100)
    Screen.Place(f, "window")
    Screen.Register("window", f)
    c:joinRaid(true)
    eq(f:IsShown(), true, "off by default")
    c:joinRaid(false)
    Options.Set("hideInRaid", true)
    c:joinRaid(true)
    eq(f:IsShown(), false)
    c:joinRaid(false)
    eq(f:IsShown(), true)
    c:joinRaid(true)
    Options.Set("hideInRaid", false)
    eq(f:IsShown(), true, "switching it off shows the windows at once")
    c:joinRaid(false)
  end)
end)

test("a profile switch puts every registered window at that profile's place", function()
  local c = sample():login()
  local Options, Screen = c.G.Noir.Options, c.G.Noir.Screen
  local f = frame(c, 200, 100)
  Screen.Place(f, "window")
  Screen.Register("window", f)
  Options.NewProfile("Other")
  Options.UseProfile("Other")
  Options.SavePosition("window", { "TOPLEFT", "BOTTOMLEFT", 300, 400 })
  Options.UseProfile("Default")
  near((c:rectOf(f)), 20, 1e-6)
  Options.UseProfile("Other")
  eq({ c:rectOf(f) }, { 300, 300, 500, 400 })
  Options.ResetProfile()
  near((c:rectOf(f)), 20, 1e-6, "a reset profile puts the window back at its default")
  eq(c:offScreen(), {})
end)
