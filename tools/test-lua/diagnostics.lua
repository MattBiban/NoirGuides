local function report(D, index)
  return table.concat(D.Lines(index), "\n")
end

test("the report names the section, the place and each line's state on the cards", function()
  local c, D, Noir = start({ level = 1, screen = { w = 1920, h = 1080, scale = 0.64 } })
  c:acceptQuest(363)
  c:advance(0.5)
  local text = report(D)
  has(text, "Section: undead-01-03-deathknell (1-3 Deathknell), chosen auto")
  local _, index, count = Noir.Progress.Place()
  has(text, string.format("Place: step %d of %d, t363.a364.a376", index, count))
  has(text, "Card current t363.a364.a376:")
  has(text, "1 turnin 363: todo")
  has(text, "2 accept 364: todo")
  has(text, "3 accept 376: todo")
  has(text, "Reminders open: none")
  -- The work goes on: each line's state follows, with the evidence for a done line.
  c:turnInQuest(363)
  c:acceptQuest(364)
  c:acceptQuest(376)
  c:advance(0.5)
  c:acceptQuest(3901)
  c:advance(0.5)
  text = report(D)
  has(text, "Card reminder r3901:")
  has(text, "1 objective 3901: todo")
  has(text, "Reminders open: r3901")
  local _, now = Noir.Progress.Place()
  has(text, "Place: step " .. now .. " of ")
  -- Options that differ from the defaults, the profile and the screen.
  ok(Noir.Options.Set("arrowScale", 1.5))
  ok(Noir.Options.Set("dialogue", false))
  text = report(D)
  has(text, "Options changed: arrowScale = 1.5, dialogue = false")
  has(text, "Profile: Default")
  has(text, "UI scale 0.64")
  has(text, "Automation: autoQuests on, flights on, hearth on, dialogue off")
end)

test("a report from the step menu names the step it was asked about", function()
  local c, D, Noir = start({ level = 1 })
  local steps = Noir.Progress.Steps()
  D.Open(3)
  has(D.Read().text, "Reported step: 3 " .. steps[3].id)
  ok(D.Read().text:find("Options changed: none", 1, true), "no option changed")
  eq(c:offScreen(), {})
end)

