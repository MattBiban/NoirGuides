-- Diagnostics.lua: /noir bug gathers what a bug report needs into a box the player can copy from.
use("tools/test-lua/sample/ports.lua")

local function start(opts)
  opts = opts or {}
  opts.race, opts.class = opts.race or "Undead", opts.class or "ROGUE"
  local c = ported(opts):login()
  return c, c.G.Noir.Diagnostics, c.G.Noir
end

for _, api in ipairs({ "classic", "modern" }) do
  -- The section, the place and the cards are in the cases below.
  test(api .. ": the report says who, where and which route", function()
    local c, D = start({ api = api, level = 3 })
    c:acceptQuest(364)
    local text = table.concat(D.Lines(), "\n")
    ok(text:match("^Noir Guides %d+%.%d+%.%d+ bug report") ~= nil, "the report starts with the version from the toc")
    has(text, "Client: 1.60.1 (70888), interface 16001")
    has(text, "Character: Undead ROGUE (Horde), level 3")
    has(text, "Route: horde-undead")
    has(text, "Position: zone 85 at 30.0, 71.0 (map 1420)")
    has(text, "Quest log (1): 364")
  end)
end

test("/noir bug opens a box with the report, selected for copying", function()
  local c, D = start()
  c:slash("/noir bug")
  local view = D.Read()
  eq(view.shown, true)
  has(view.text, "bug report")
  ok(D.box:HasFocus(), "the box has the keyboard")
  ok(D.box.__highlight, "the text is selected")
  has(c:chatText(), "Ctrl+C")
end)

test("Escape closes the box, and the text cannot be changed by typing", function()
  local c, D = start()
  D.Open()
  local text = D.box:GetText()
  D.box:SetText("typed over")
  c:callAddon(D.box:GetScript("OnTextChanged"), D.box, true)
  eq(D.box:GetText(), text)
  c:callAddon(D.box:GetScript("OnEscapePressed"), D.box)
  eq(D.Read().shown, false)
end)

test("the why-log, the problems and errors are in the report", function()
  local c, D, Noir = start()
  Noir.Why.Add({ section = "undead-01-03-deathknell", step = "t363.a364.a376", n = 2, kind = "tick", text = "you skipped it" })
  Noir.Problem("Something odd happened.")
  Noir.ReportError("Interface/AddOns/NoirGuides/Progress.lua:1: boom")
  c:takeErrors()
  local text = table.concat(D.Lines(), "\n")
  has(text, "you skipped it")
  has(text, "Something odd happened.")
  has(text, "boom")
end)

test("errors in event handlers, timers and commands reach the report, not only Noir.ReportError", function()
  local c, D, Noir = start()
  Noir.On("NOIR_TEST_BOOM", function() error("handler boom") end)
  Noir.Fire("NOIR_TEST_BOOM")
  Noir.After(0.1, function() error("timer boom") end)
  c:advance(0.5, 0.25)
  Noir.Command("testboom", "raises", function() error("command boom") end)
  c:slash("/noir testboom")
  c:takeErrors()
  local text = table.concat(D.Lines(), "\n")
  has(text, "Errors (3):")
  has(text, "handler boom")
  has(text, "timer boom")
  has(text, "command boom")
end)

test("the report talks about talents and professions", function()
  local c, D = start({ level = 12 })
  c:setProfession(393, "Skinning", 50, 75)
  local text = table.concat(D.Lines(), "\n")
  has(text, "Talents: Combat build fits, 3 points to spend")
  has(text, "Professions: Skinning 50/75")
end)

test("without a route or a position the report still comes out", function()
  local c = ported({ race = "Orc", zone = 14, swap = { { match = "^Data/", with = { SAMPLE3_DATA } }, { match = "^Routes/", with = {} } } }):login()
  c:moveTo({ hidden = true })
  local text = table.concat(c.G.Noir.Diagnostics.Lines(), "\n")
  has(text, "Route: none")
  has(text, "Position: unknown")
  c:slash("/noir bug")
end)

test("the box never gets a font object; with no usable font it stays empty and raises nothing", function()
