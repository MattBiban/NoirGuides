// SkillLine categories: 11 the primary professions, 9 the secondary skills (First Aid, Cooking, Fishing).
const CATEGORY = { 11: "primary", 9: "secondary" };

// -> { professions: { skillLine: { name, kind } }, lines: { tierLine: skillLine } }
// A profession is a top-level skill line of one of the two categories with a tier line under it: Forever files each
// profession's ranks as a child line ("Skinning" 2947 under 393), and in this build every one of those sits at
// ParentTierIndex 4. That leaves out the rogues' Poisons (category 9, its child at tier index 1) and the client's
// test lines, whose names end in [DNT].
function loadProfessions(dataDir) {
  const rows = readCsv(path.join(dataDir, "wago", "SkillLine.csv"));
  const TIER_INDEX = 4;
  const parents = new Set(rows.filter((r) => +r.ParentSkillLineID > 0 && +r.ParentTierIndex === TIER_INDEX).map((r) => +r.ParentSkillLineID));
  const professions = {};
  for (const r of rows) {
    if (+r.ParentSkillLineID === 0 && CATEGORY[+r.CategoryID] && parents.has(+r.ID) && !r.DisplayName_lang.includes("[DNT]")) {
      professions[+r.ID] = { name: r.DisplayName_lang, kind: CATEGORY[+r.CategoryID] };
    }
  }
  const lines = {};
  for (const r of rows) if (professions[+r.ParentSkillLineID]) lines[+r.ID] = +r.ParentSkillLineID;
  return { professions, lines };
}

function professionsLua({ professions, lines }, { build = SOURCES.wago.build } = {}) {
  const ids = (t) => Object.keys(t).map(Number).sort((a, b) => a - b);
  return [HEADER.trimEnd(),
    `-- Generated by tools/gen_ports.js from the client's SkillLine table (wago.tools, build ${build}). Do not edit by hand.`,
    "--   Noir.Data.professions[skillLine] = { name, kind = \"primary\" | \"secondary\" }",
    "--   Noir.Data.professionLines[line] = skillLine   Forever's tier lines, each under its profession",
    "Noir.Data.professions = {",
    ...ids(professions).map((id) => `  [${id}] = { name = ${luaString(professions[id].name)}, kind = ${luaString(professions[id].kind)} },`),
    "}",
    "Noir.Data.professionLines = {",
    ...ids(lines).map((id) => `  [${id}] = ${lines[id]},`),
    "}", ""].join("\n");
}

// ---------------------------------------------------------------------------------------------------------------
// Quest cleanup: what ties a quest to more than its giver
// ---------------------------------------------------------------------------------------------------------------
//
// The cleanup (NoirGuides/Cleanup.lua) asks one question of a quest the route no longer needs: if the player drops
// it, can it simply be taken again from its giver? This writes the facts that answer it, per quest, and no verdict:
//   classes   the classes that may take it (the planner's class mask, lib/db.js, which also reads class quest sorts)
//   skill     the profession it needs (requiredSkill, Forever's tier lines folded into their profession, or a quest
//             sort named after a profession), a SkillLine ID
//   instance  the dungeon or raid it is done in, by name (lib/quests.js instanced())
//   event     the world event it belongs to: a quest sort whose quests are only offered while that event runs
//   item      the name of the item it starts from (an item may not drop a second time)
// Cleanup.lua decides from these and from the character what to list and in which group.

// QuestSort names whose quests are offered only during an event. Read from the client's QuestSort table: every
// event sort that holds a quest in the Forever data (Nightmare Incursions and Blackrock Eruption hold none).
const EVENT_SORT_NAMES = new Set(["Seasonal", "Special", "Darkmoon Faire", "Ahn'Qiraj War", "Lunar Festival", "Invasion", "Midsummer"]);
const CLASS_BY_BIT = Object.entries(CLASSES).sort((a, b) => a[1] - b[1]);

// quests: [{ id, classes (mask), sort, zone, requiredSkill, starts: { items } }]
// ctx: { sortName(id), professions, lines, instanceName(zone), itemName(id) } -> { questId: ties }
function questTies(quests, ctx) {
  const skillByName = new Map(Object.entries(ctx.professions).map(([id, p]) => [p.name, +id]));
  const out = {};
  for (const q of quests) {
    const ties = {};
    const classes = CLASS_BY_BIT.filter(([, id]) => q.classes && hasBit(q.classes, id - 1)).map(([token]) => token);
    if (classes.length) ties.classes = classes;
    const sortName = q.sort < 0 ? ctx.sortName(-q.sort) : undefined;
    const needed = Array.isArray(q.requiredSkill) ? +q.requiredSkill[0] : 0;
    const skill = needed ? (ctx.lines[needed] || needed) : skillByName.get(sortName);
    if (skill) ties.skill = skill;
    const instance = q.zone > 0 ? ctx.instanceName(q.zone) : null;
    if (instance) ties.instance = instance;
    if (EVENT_SORT_NAMES.has(sortName)) ties.event = sortName;
    const item = q.starts.items.map((id) => ctx.itemName(id)).find(Boolean);
    if (item) ties.item = item;
    if (Object.keys(ties).length) out[q.id] = ties;
  }
  return out;
}

function loadQuestTies(dataDir) {
  const db = loadDb(dataDir);
  const raw = JSON.parse(fs.readFileSync(path.join(dataDir, "forever_db.json"), "utf8")).Quest;
  const sorts = new Map(readCsv(path.join(dataDir, "wago", "QuestSort.csv")).map((r) => [+r.ID, r.SortName_lang]));
  const { professions, lines } = loadProfessions(dataDir);
  const quests = [...db.quests.values()].map((q) => ({ ...q, requiredSkill: (raw[q.id] || {}).requiredSkill }));
  return questTies(quests, {
    sortName: (id) => sorts.get(id),
    professions,
    lines,
    instanceName: (zone) => (instanced(db, zone) && db.areas.has(zone) ? db.areas.get(zone).name : null),
    itemName: (id) => (db.items.get(id) || {}).name || null,
  });
}

function questTiesLua(ties, { release = SOURCES.questiedb.release } = {}) {
  const field = (key, v) => `${key} = ${Array.isArray(v) ? `{ ${v.map(luaString).join(", ")} }` : typeof v === "number" ? v : luaString(v)}`;
  const ORDER = ["classes", "skill", "instance", "event", "item"];
  const row = (id) => `  [${id}] = { ${ORDER.filter((k) => ties[id][k] !== undefined).map((k) => field(k, ties[id][k])).join(", ")} },`;
  return [HEADER.trimEnd(),
    `-- Generated by tools/gen_ports.js from QuestieDB Forever ${release} and the client's QuestSort, SkillLine and AreaTable`,
    "-- tables. Do not edit by hand.",
    "--   Noir.Data.questTies[questId] = { classes = { token, ... }, skill = skillLine, instance = name, event = name,",
    "--                                    item = name }   only the fields that apply; quests with none are left out",
    "Noir.Data.questTies = {", ...Object.keys(ties).map(Number).sort((a, b) => a - b).map(row), "}", ""].join("\n");
}

// ---------------------------------------------------------------------------------------------------------------

function generate(dataDir = DATA) {
  return {
    "Talents.lua": talentsLua(loadTrees(dataDir), BUILDS),
    "Professions.lua": professionsLua(loadProfessions(dataDir)),
    "Cleanup.lua": questTiesLua(loadQuestTies(dataDir)),
  };
}

if (require.main === module) {
  fs.mkdirSync(OUT, { recursive: true });
  for (const [name, text] of Object.entries(generate())) {
    fs.writeFileSync(path.join(OUT, name), text);
    console.log(`NoirGuides/Data/${name}: ${text.split("\n").length} lines`);
  }
}

module.exports = { talentsLua, professionsLua, questTies, questTiesLua, loadProfessions, loadQuestTies, generate };
