// CLI: npm run ports. Writes the data of the ported modules (task X2) to NoirGuides/Data/ from tools/data/:
//   Talents.lua      the client's talent trees for every class and one leveling build each (lib/talent_builds.js),
//                    refused when a build cannot be learned point by point (lib/talents.js)
//   Professions.lua  the professions by skill line (SkillLine), and Forever's tier lines that point to them
//   Cleanup.lua      what ties each quest to more than its giver (class, skill, instance, event, starting item)
// Deterministic: the same data gives the same files. tools/test/ports.test.js checks that the files are current.
const fs = require("fs");
const path = require("path");
const { readCsv } = require("./lib/csv");
const { loadDb } = require("./lib/db");
const { instanced } = require("./lib/quests");
const { CLASSES, hasBit } = require("./lib/characters");
const { loadTrees, expand, checkBuild, POINTS } = require("./lib/talents");
const { BUILDS } = require("./lib/talent_builds");

const DATA = path.join(__dirname, "data");
const OUT = path.join(__dirname, "..", "NoirGuides", "Data");
const SOURCES = JSON.parse(fs.readFileSync(path.join(__dirname, "data_sources.json"), "utf8"));
const HEADER = "-- Noir Guides, GPLv3. See LICENSE.\n";

const luaString = (s) => JSON.stringify(String(s));

// ---------------------------------------------------------------------------------------------------------------
// Talents
// ---------------------------------------------------------------------------------------------------------------

function talentLine(t) {
  const fields = [`id = ${t.id}`];
  if (t.name) fields.push(`name = ${luaString(t.name)}`);
  fields.push(`tier = ${t.tier}`, `column = ${t.column}`, `max = ${t.max}`);
  if (t.prereq) fields.push(`prereq = ${t.prereq}`, `prereqRank = ${t.prereqRank}`);
  return `{ ${fields.join(", ")} }`;
}

// trees: classToken -> { tabs }; builds: classToken -> { spec, picks }. Throws when a build is not learnable.
function talentsLua(trees, builds, { build = SOURCES.wago.build, points = POINTS } = {}) {
  const out = [HEADER.trimEnd(),
    `-- Generated by tools/gen_ports.js from the client's Talent, TalentTab and SpellName tables (wago.tools, build ${build})`,
    "-- and the builds in tools/lib/talent_builds.js. Do not edit by hand.",
    "--   Noir.Data.talents[CLASS] = { spec, tabs = { { id, name, talents = { { id, name, tier, column, max [, prereq,",
    "--     prereqRank] } } } }, build = { talent ID for each point from level 10 } }",
    "-- Tabs are in the client's order; tier and column are 1-based as the game's talent functions count them. A talent",
    "-- the data has no name for has none here: the engine then takes the client's.",
    "Noir.Data.talents = {"];
  for (const cls of Object.keys(builds).sort()) {
    const tree = trees[cls];
    if (!tree) throw new Error(`${cls}: no talent trees in the data`);
    const ids = expand(builds[cls].picks);
    const problems = checkBuild(tree, ids, { points });
    if (problems.length) throw new Error(`${cls}: the build cannot be learned: ${problems.join("; ")}`);
    out.push(`  ${cls} = {`, `    spec = ${luaString(builds[cls].spec)},`, "    tabs = {");
    for (const tab of tree.tabs) {
      out.push(`      { id = ${tab.id}, name = ${luaString(tab.name)}, talents = {`);
      for (const t of tab.talents) out.push(`        ${talentLine(t)},`);
      out.push("      } },");
    }
    out.push("    },", `    build = { ${ids.join(", ")} },`, "  },");
  }
  out.push("}", "");
  return out.join("\n");
}

