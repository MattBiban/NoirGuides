// The three data files the engine reads beside the format 3 routes (planner/emit3.js writes the routes themselves):
// Names.lua, Zones.lua, Flights.lua. Every list sorted by ID, so the same routes always give the same bytes.
//   emitNames(db, routes3), emitZones(db, routes3, graph), emitFlights(graph)
// emitLua writes a format 2 route; only tools/sim_all.js and its test read that form until task X1 moves the
// simulator to format 3.
const fs = require("fs");
const path = require("path");

const LICENSE = "-- Noir Guides, GPLv3. See LICENSE.";
// The keys of a step in the order they are written. `to` is a flight point's ID on a fly step and a place on a
// transport or hearth step; "do" is a Lua keyword, hence "action".
const KEYS = ["action", "quest", "node", "from", "to:number", "kind", "level", "at", "to:place", "npc", "object", "item", "when"];
const KNOWN = new Set(KEYS.map((k) => k.split(":")[0]));

const release = () => JSON.parse(fs.readFileSync(path.join(__dirname, "..", "data_sources.json"), "utf8")).questiedb.release;
// A Lua string: only the backslash, the quote and line breaks need an escape; everything else is written as it is.
const str = (s) => `"${String(s).replace(/\\/g, "\\\\").replace(/"/g, '\\"').replace(/\r/g, "\\r").replace(/\n/g, "\\n")}"`;
const place = (p) => `{ zone = ${p.zone}, x = ${p.x}, y = ${p.y} }`;

function value(key, v) {
  if (key === "at" || key === "to:place") return place(v);
  if (key === "when") {
    const parts = [];
    if (v.class !== undefined) parts.push(`class = ${str(v.class)}`);
    if (v.level !== undefined) parts.push(`level = ${v.level}`);
    return `{ ${parts.join(", ")} }`;
  }
  return typeof v === "string" ? str(v) : String(v);
}
function stepLua(step) {
  for (const key of Object.keys(step)) if (!KNOWN.has(key)) throw new Error(`a ${step.action} step has the key "${key}", which route format 2 does not know`);
  const parts = [];
  for (const key of KEYS) {
    const [name, kind] = key.split(":");
    const v = step[name];
    if (v === undefined || (kind === "number" && typeof v !== "number") || (kind === "place" && typeof v !== "object")) continue;
    parts.push(`${name} = ${value(key, v)}`);
  }
  return `    { ${parts.join(", ")} },`;
}
const header = (what) => [LICENSE, `-- Generated by tools/build_routes.js from ${what}. Do not edit.`];

function emitLua(route) {
  return [
    ...header(`QuestieDB Forever ${release()}`),
    `Noir.Route(${str(route.id)}, {`,
    `  format = 2, race = ${str(route.race)}, faction = ${str(route.faction)},`,
    "  steps = {",
    ...route.steps.map(stepLua),
    "  },",
    "})",
    "",
  ].join("\n");
}

const sorted = (set) => [...set].sort((a, b) => a - b);
// Every step of every format 3 route, with its section.
function* stepsOf(routes) {
  for (const route of routes) {
    if (route.format !== 3) throw new Error(`route ${route.id} is in format ${route.format}; the data files are written from format 3 routes`);
    for (const section of route.sections) for (const step of section.steps) yield { section, step };
  }
}
// Names.lua: the name of every quest, NPC, object and item the routes name (lines, item buttons, target buttons), and
// nothing else.
function emitNames(db, routes) {
  const ids = { quests: new Set(), npcs: new Set(), objects: new Set(), items: new Set() };
  const add = (kind, id) => { if (Number.isInteger(id) && id > 0) ids[kind].add(id); };
  for (const { step } of stepsOf(routes)) {
    for (const line of step.lines) {
      add("quests", line.quest); add("quests", line.ifDone);
      for (const q of line.requires || []) add("quests", q);
      add("npcs", line.npc); add("objects", line.object); add("items", line.item);
      if (line.buy) add("items", line.buy.item);
    }
    for (const id of step.items || []) add("items", id);
    for (const id of (step.targets && step.targets.enemy) || []) add("npcs", id);
    for (const id of (step.targets && step.targets.friend) || []) add("npcs", id);
  }
  const out = header(`QuestieDB Forever ${release()}`);
  for (const [kind, table] of [["quests", db.quests], ["npcs", db.npcs], ["objects", db.objects], ["items", db.items]]) {
    for (const id of sorted(ids[kind])) {
      const entry = table.get(id);
      if (entry && entry.name) out.push(`Noir.Data.${kind}[${id}] = ${str(entry.name)}`);
    }
  }
  return out.join("\n") + "\n";
}
// Zones.lua: every zone a route or a flight point names, with its map and its continent (the client's map ID: 0, 1, 2991).
function emitZones(db, routes, graph) {
  const zones = new Set();
  for (const { section, step } of stepsOf(routes)) {
    zones.add(section.zone);
    if (step.at) zones.add(step.at.zone);
    for (const line of step.lines) for (const p of [line.at, typeof line.to === "object" ? line.to : null]) if (p) zones.add(p.zone);
  }
  for (const node of graph.nodes.values()) zones.add(node.point.zone);
  const out = header("the client's AreaTable and UiMapAssignment");
  for (const zone of sorted(zones)) {
    const map = db.maps.get(zone), area = db.areas.get(zone);
    if (map && area) out.push(`Noir.Data.zones[${zone}] = { uiMap = ${map.uiMap}, name = ${str(area.name)}, continent = ${area.continent} }`);
  }
  return out.join("\n") + "\n";
}
// Flights.lua: every flight point a character can learn, where its flight master stands, and whose it is (factions:
// "A", "H" or "AH"). A point both factions use is written once, at the first faction's flight master. Neutral towns have
// one point per faction under the same name (Booty Bay is 18 and 19): the engine tells them apart by faction.
function emitFlights(graph) {
  const round2 = (n) => Math.round(n * 100) / 100;
  const out = header("the client's TaxiNodes and QuestieDB's flight masters");
  for (const id of sorted(graph.nodes.keys())) {
    const node = graph.nodes.get(id);
    const factions = node.factions.map((f) => f[0]).sort().join("");
    out.push(`Noir.Data.flights[${id}] = { name = ${str(node.name)}, zone = ${node.point.zone}, x = ${round2(node.point.x)}, y = ${round2(node.point.y)}, factions = "${factions}" }`);
  }
  return out.join("\n") + "\n";
}

module.exports = { emitLua, emitNames, emitZones, emitFlights };
