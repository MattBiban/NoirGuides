// Reads the text the way the addon does: Noir.Route(id, data) is called once.
function readBack(lua) {
  const vm = createVm({ print() {} });
  assert.strictEqual(vm.run("Noir = { Route = function(id, data) CAUGHT = { id = id, data = data } return true end }", "=stub"), null);
  assert.strictEqual(vm.run(lua, "=route"), null);
  return vm.value("return CAUGHT", "=caught");
}

test("the same route gives the same bytes", () => {
  const a = emitRoute3(sample()), b = emitRoute3(sample());
  assert.strictEqual(a, b);
  // key order in the input does not matter
  const shuffled = sample();
  shuffled.sections[0] = Object.fromEntries(Object.entries(shuffled.sections[0]).reverse());
  shuffled.sections[0].steps[0] = Object.fromEntries(Object.entries(shuffled.sections[0].steps[0]).reverse());
  assert.strictEqual(emitRoute3(shuffled), a);
  const lines = a.split("\n");
  assert.strictEqual(lines[0], "-- Noir Guides, GPLv3. See LICENSE.");
  assert.match(lines[1], /^-- Generated by tools\/build_routes\.js from QuestieDB Forever v[\d.]+\. Do not edit\.$/);
  assert.strictEqual(lines[2], 'Noir.Route("horde-undead", {');
  assert.strictEqual(lines[3], '  format = 3, race = "Undead", faction = "Horde",');
  assert.ok(lines.includes('            { kind = "turnin", quest = 364, npc = 1569 },'), "one line per route line");
  assert.ok(lines.includes('            { kind = "accept", quest = 365, npc = 1569, requires = { 8, 364 } },'), "lists without meaning in their order are sorted");
  assert.ok(a.endsWith("})\n"));
  luaparse.parse(a, { luaVersion: "5.1" });
});

test("the text reads back through the Lua VM as the same table", () => {
  const route = sample();
  const back = readBack(emitRoute3(route));
  assert.strictEqual(back.id, "horde-undead");
  const want = clone(route);
  delete want.id;
  want.sections[0].steps[0].lines[1].requires = [8, 364];
  assert.deepStrictEqual(back.data, want);
  assert.strictEqual(checkRoute3(back.data), null);
});

test("a route that fails checkRoute3 is refused", () => {
  const bad = sample();
  bad.sections[0].steps[0].text = "x".repeat(161);
  assert.throws(() => emitRoute3(bad), /text is longer than 160 characters/);
  const two = sample();
  two.sections[1].start = true;
  assert.throws(() => emitRoute3(two), /2 start sections/);
});
